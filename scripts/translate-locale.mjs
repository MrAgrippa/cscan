function translate(value) {
  if (typeof value !== "string") return value
  // Точное совпадение
  if (Object.prototype.hasOwnProperty.call(dict, value)) {
    return dict[value]
  }
  // Возвращаем английский по умолчанию (vue-i18n будет показывать как есть)
  return value
}

function walk(obj) {
  if (obj === null || obj === undefined) return obj
  if (Array.isArray(obj)) return obj.map(walk)
  if (typeof obj === "object") {
    const out = {}
    for (const k of Object.keys(obj)) {
      out[k] = walk(obj[k])
    }
    return out
  }
  return translate(obj)
}

const enContent = JSON.parse(fs.readFileSync(EN_PATH, "utf-8"))
const ruContent = walk(enContent)
fs.writeFileSync(RU_PATH, JSON.stringify(ruContent, null, 2) + "\n", "utf-8")

// Подсчёт статистики
let total = 0
let translated = 0
function count(node) {
  if (typeof node === "string") {
    total++
    if (Object.values(dict).includes(node)) translated++
    return
  }
  if (typeof node === "object" && node !== null) {
    for (const v of Object.values(node)) count(v)
  }
}
count(ruContent)
console.log(`[ru-RU] Strings total: ${total}, translated: ${translated} (${((translated / total) * 100).toFixed(1)}%)`)
console.log(`[ru-RU] Written to: ${RU_PATH}`)
